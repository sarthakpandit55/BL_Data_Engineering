-- CROSS Join
SELECT * FROM CUSTOMER CROSS JOIN EMPLOYEE;


-- INNER Join
SELECT * FROM EMPLOYEE
INNER JOIN CUSTOMER
ON EMPLOYEE.fname = CUSTOMER.fname

-- LEFT Join
SELECT * FROM EMPLOYEE
LEFT JOIN CUSTOMER
ON EMPLOYEE.fname = CUSTOMER.fname;

-- RIGHT Join
SELECT * FROM EMPLOYEE
RIGHT JOIN CUSTOMER
ON EMPLOYEE.fname = CUSTOMER.fname;